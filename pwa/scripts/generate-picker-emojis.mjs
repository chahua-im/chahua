import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import rgiEmoji from 'regenerate-unicode-properties/Property_of_Strings/RGI_Emoji.js';

const sequences = [...rgiEmoji.characters.toArray().map((point) => String.fromCodePoint(point)), ...rgiEmoji.strings];
const qualified = new Map(sequences.map((char) => [char.replace(/\uFE0F/g, ''), char]));
// Emojibase's display string can add optional VS16 (e.g. 👍️). Use the same RGI
// spelling as input validation and existing reactions, while preserving required VS16 (❤️).
function canonical(emoji) {
  const char = qualified.get(emoji.emoji.replace(/\uFE0F/g, ''));
  assert(char, `Missing Unicode sequence: ${emoji.emoji}`);
  return char;
}

const packageRoot = new URL('../node_modules/emojibase-data/', import.meta.url);
const { version } = JSON.parse(await readFile(new URL('package.json', packageRoot), 'utf8'));
const locales = await Promise.all(
  ['en', 'zh', 'zh-hant'].map(async (locale) =>
    JSON.parse(await readFile(new URL(`${locale}/data.json`, packageRoot), 'utf8')),
  ),
);
const translations = locales.map(
  (data) => new Map(data.flatMap((emoji) => [emoji, ...(emoji.skins ?? [])]).map((emoji) => [emoji.emoji, emoji])),
);
// The picker has no Components tab; place skin/hair components with People.
const categories = [
  'smileys',
  'people',
  'people',
  'animals',
  'food',
  'travel',
  'activities',
  'objects',
  'symbols',
  'flags',
];
const entries = [];
for (const emoji of locales[0]) {
  // Regional indicator letters have no group and are not standalone emoji.
  if (emoji.group == null) continue;
  const category = categories[emoji.group];
  assert(category, `Unknown emoji group: ${emoji.group}`);
  const skins = (emoji.skins ?? []).filter((skin) => typeof skin.tone === 'number').sort((a, b) => a.tone - b.tone);
  if (skins.length)
    assert.deepEqual(
      skins.map((skin) => skin.tone),
      [1, 2, 3, 4, 5],
    );
  for (const item of [emoji, ...(emoji.skins ?? []).filter((skin) => Array.isArray(skin.tone))]) {
    const hasSkinTone = item === emoji && skins.length > 0;
    entries.push({
      char: canonical(item),
      name: item.label,
      keywords: [
        ...new Set(
          translations.flatMap((data) => {
            const base = data.get(emoji.emoji);
            const localized = data.get(item.emoji);
            assert(localized, `Missing translation for ${item.emoji}`);
            return [localized.label, ...(localized.tags ?? []), ...(base.tags ?? [])];
          }),
        ),
      ],
      category,
      hasSkinTone,
      ...(hasSkinTone ? { base: canonical(emoji), skins: skins.map(canonical) } : {}),
    });
  }
}
assert.equal(new Set(entries.map((entry) => entry.char)).size, entries.length);
const selectable = new Set(entries.flatMap((entry) => [entry.char, ...(entry.skins ?? [])]));
assert.deepEqual(
  sequences.filter((char) => !selectable.has(char)),
  [],
  'Picker must cover all RGI emoji sequences',
);

await writeFile(
  new URL('../public/emoji-data-LICENSE.txt', import.meta.url),
  `emojibase-data ${version}\n\n${await readFile(new URL('LICENSE', packageRoot), 'utf8')}\nUnicode data: https://www.unicode.org/license.txt\n`,
);
const outputPath = fileURLToPath(
  new URL('../src/app/messages/emoji-picker/picker-emojis.generated.json', import.meta.url),
);
await writeFile(
  outputPath,
  await format(
    JSON.stringify({
      source: `emojibase-data ${version}; generated by npm run emoji:picker:generate`,
      license: 'MIT (emojibase-data); Unicode data: https://www.unicode.org/license.txt',
      emojis: entries,
    }),
    { ...(await resolveConfig(outputPath)), filepath: outputPath },
  ),
);
console.log(`Generated ${entries.length} picker entries from emojibase-data ${version}.`);
