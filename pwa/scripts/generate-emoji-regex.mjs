import { writeFile } from 'node:fs/promises';
import rewritePattern from 'regexpu-core';
import unicodeVersion from 'regenerate-unicode-properties/unicode-version.js';

const pattern = rewritePattern('\\p{RGI_Emoji}', 'gv', {
  unicodeSetsFlag: 'transform',
  unicodePropertyEscapes: 'transform',
  unicodeFlag: 'transform',
});

await writeFile(
  new URL('../src/app/settings/emoji-sequences.ts', import.meta.url),
  `// Generated by npm run emoji:generate; Unicode ${unicodeVersion}. Do not edit manually.
const RGI_EMOJI = /${pattern}/g;

/** Extracts complete emoji sequences in order, dropping plain text and whitespace. */
export function extractEmojiSequences(value: string): string[] {
  return value.match(RGI_EMOJI) ?? [];
}
`,
);
